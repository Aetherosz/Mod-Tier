"""Writes Source/TidyMilestones/Private/AetheroszNames.inl from Docs/AetheroszNames.json.
Run after editing the JSON. The preset is compiled in so it can't go missing from a package."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "Docs/AetheroszNames.json").read_text(encoding="utf-8"))
text = json.dumps(data, ensure_ascii=True, separators=(",", ":"))  # ASCII only: no source-encoding surprises
assert ")JSON" not in text and len(text) < 16000, "split the literal"
out = root / "Source/TidyMilestones/Private/AetheroszNames.inl"
out.write_text("// Generated by Tools/make_preset.py from Docs/AetheroszNames.json. Do not edit.\n"
               'static const TCHAR* const AetheroszNamesJson = TEXT(R"JSON(' + text + ')JSON");\n', encoding="utf-8")
print(len(data["overrides"]), "entries,", len(text), "chars")
